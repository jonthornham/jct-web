// Optimised photos for the site (lamp-web's image pipeline).
//
//   npm run images
//
// Reads the originals from the design bundle (design/jct-download-01/assets/images; they stay
// there, untouched) and writes, for each image and width, AVIF, WebP and a JPEG fallback to
// static/img/<name>-<width>.<ext>. It also writes src/lib/images.js, the manifest
// ResponsiveImage reads (widths, intrinsic size, fallback type), and prints the byte table.
// Re-run it after adding an image or changing a width.
import { mkdirSync, statSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const SRC = 'design/jct-download-01/assets/images';
const OUT = 'static/img';

// Widths follow where each image is shown (assets/ASSETS.md), up to 2× the largest display size
// and never past the original.
//   seltza-tap      Home hero (≈470px column at 1440), Work · Seltza. Original 1040 wide.
//   flo-64-as-disc  Work · FLO, 4:5 on a white plate. Original 1000 wide.
//   jon-thornham    About (4:5, ≈420px), Free Consult (56px circle). Original 1000 wide.
const IMAGES = [
	{ name: 'seltza-tap', file: 'seltza-tap.jpg', widths: [480, 800, 1040] },
	{ name: 'flo-64-as-disc', file: 'flo-64-as-disc.jpg', widths: [400, 800, 1000] },
	{ name: 'jon-thornham', file: 'jon-thornham.jpg', widths: [112, 480, 1000] }
];

const QUALITY = { avif: 55, webp: 78, jpg: 80 };

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const manifest = {};
const rows = [];
for (const img of IMAGES) {
	const src = join(SRC, img.file);
	const meta = await sharp(src).metadata();
	const fallback = img.alpha ? 'png' : 'jpg';
	const widths = img.widths.filter((w) => w <= meta.width);
	const out = { avif: 0, webp: 0, [fallback]: 0 };
	for (const w of widths) {
		const base = sharp(src).resize({ width: w });
		const write = async (ext, pipeline) => {
			const file = join(OUT, `${img.name}-${w}.${ext}`);
			await pipeline.toFile(file);
			const bytes = statSync(file).size;
			if (w === widths.at(-1)) out[ext] = bytes;
			return bytes;
		};
		await write('avif', base.clone().avif({ quality: QUALITY.avif, effort: 6 }));
		await write('webp', base.clone().webp({ quality: QUALITY.webp, alphaQuality: 90, effort: 6 }));
		if (fallback === 'png')
			await write(
				'png',
				base.clone().png({ palette: true, quality: 85, compressionLevel: 9, effort: 10 })
			);
		else await write('jpg', base.clone().jpeg({ quality: QUALITY.jpg, mozjpeg: true }));
	}
	manifest[img.name] = {
		width: meta.width,
		height: meta.height,
		widths,
		fallback
	};
	rows.push({ name: img.name, original: statSync(src).size, largest: widths.at(-1), ...out });
}

writeFileSync(
	'src/lib/images.js',
	`// Generated by scripts/images.mjs (npm run images). Don't edit by hand.\n// Each image: its original size and the widths written to static/img/<name>-<width>.<avif|webp|fallback>.\nexport const images = ${JSON.stringify(manifest, null, '\t')};\n`
);

// Keep the generated manifest in the repo's style, so `npm run lint` stays clean.
execFileSync('npx', ['prettier', '--write', 'src/lib/images.js'], { stdio: 'ignore' });

const kb = (n) => (n / 1024).toFixed(0).padStart(6) + ' KB';
console.log('image                  original    largest width: avif / webp / fallback');
for (const r of rows) {
	const fb = r.png ?? r.jpg;
	console.log(
		`${r.name.padEnd(22)} ${kb(r.original)}   ${String(r.largest).padStart(4)}px: ${kb(r.avif)} / ${kb(r.webp)} / ${kb(fb)}`
	);
}
